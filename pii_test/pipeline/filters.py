"""The rules that decide what a detection is worth. No models, no files read but the lists.

Three jobs:

1. Header rules: what a column header alone says about scanning it
   (headerrule), shared by the scan and by Tier 1.
2. The regex detectors: Aadhaar (with its Verhoeff check digit), PAN, phone
   and farmer registration numbers (regexmatches).
3. The filters over what the detectors found:

   * reject NER PERSON predictions that are categorically not people. Four
     mechanisms, in increasing order of generality:

     - closed vocabularies written out below -- location categories, academic
       qualifications, school schemes, management types, agricultural terms;
     - generated gazetteers under ``pii_test/gazetteer/``, one file per
       vocabulary so a rejection stays traceable and a list can be dropped
       wholesale;
     - cross-dataset frequency: a value that appears in more than a handful of
       unrelated datasets is a category, not a person. This is the only signal
       here that scales past hand-curated lists;
     - a score floor. Under the word-level ``"average"`` aggregation scan.py
       uses, NER scores separate -- see SCOREFLOOR for the measured curve.

   * decide whether a dataset as a whole should be flagged (datasetflag),
     which is a different and stricter question than whether any single cell
     matched.
"""

